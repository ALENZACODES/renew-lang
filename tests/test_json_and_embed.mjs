// Building on Renew from other code: renew run --json prints the result blocks, tables carry their numbers
// (raw) and units, values carry value and type, and examples/embed.html imports the ES module that
// compile --module makes from example 1.
import { Renew, eq, ok, done, root } from "./helpers.mjs";
import { readFileSync, writeFileSync, mkdtempSync } from "fs";
import { join } from "path";
import { tmpdir } from "os";
import { execFileSync, spawnSync } from "child_process";
const cli = (args) => execFileSync(process.execPath, [join(root, "bin/renew.js"), ...args], { encoding: "utf8" });
const ex1 = join(root, "examples/01-renewal-2026.renew"), src1 = readFileSync(ex1, "utf8");
// 1. renew run --json
const j = JSON.parse(cli(["run", ex1, "--json"]));
eq("json has the same blocks as run()", JSON.stringify(j.blocks), JSON.stringify(Renew.run(src1).blocks));
eq("block kinds in order", j.blocks.map((b) => b.kind).join(","), "value,value,table,value,value,table,value,explain,check");
const t = j.blocks[2];
eq("compare columns", t.columns.join("|"), "Plan|Payment|Interest over 5 years|Paid over 5 years|Balance after 5 years|Time to pay off");
eq("compare units", t.units.join("|"), "text|money|money|money|money|duration");
eq("compare raw row", JSON.stringify(t.raw[1]), '["Offered 5 year",2824.98,94169.01,169498.8,365733.54,240]');
ok("every raw money figure matches its text", t.raw.every((row, i) => row.every((x, k) => t.units[k] !== "money" || t.rows[i][k].startsWith(Renew.kernel.money(x)))));
const sw = j.blocks[5];
eq("sweep raw first column is the rate", JSON.stringify(sw.raw.map((x) => x[0])), '[3.5,4,4.5,5,5.5,6,"Offered 5 year (for comparison)"]');
eq("sweep first unit", sw.units[0], "percent");
eq("value block value and type", JSON.stringify([j.blocks[0].value, j.blocks[0].type]), '[2848.54,"money"]');
eq("points type", JSON.stringify([j.blocks[3].value, j.blocks[3].type]), '[1.5,"points"]');
eq("money value rounded to the cent", j.blocks[4].value, 31219.6);
eq("break even value", JSON.stringify([j.blocks[6].value, j.blocks[6].type]), '[4.889,"percent"]');
eq("check block", j.blocks[8].pass, true);
const sched = Renew.run('mortgage "A"\n  balance $100,000\n  rate 5%\n  amortization 25 years\n  term 1 year\nshow schedule "A" first 2\nshow yearly "A"\n').blocks;
eq("schedule raw", JSON.stringify(sched[0].raw[0]), "[1,581.6,412.39,169.21,99830.79]");
eq("yearly raw", sched[1].raw[0][0], 1);
const jin = JSON.parse(cli(["run", ex1, "--input", "discount=1%", "--json"]));
eq("--json with --input", jin.blocks[6].value, 5.388);
eq("--json on compile is a usage error", spawnSync(process.execPath, [join(root, "bin/renew.js"), "compile", ex1, "--json"]).status, 2);
const dir = mkdtempSync(join(tmpdir(), "renewj-"));
writeFileSync(join(dir, "bad.renew"), 'mortgage "A"\n  balance 5\n');
const bad = spawnSync(process.execPath, [join(root, "bin/renew.js"), "run", join(dir, "bad.renew"), "--json"], { encoding: "utf8" });
ok("--json errors still go to stderr with exit 1", bad.status === 1 && bad.stdout === "" && bad.stderr.includes("Line 2, column 11"));
// 2. The embed module is the compile --module output of example 1, kept up to date by npm run build.
const mod = readFileSync(join(root, "examples/embed/renewal-2026.mjs"), "utf8");
eq("embed module is fresh", mod, "// Generated by scripts/make_examples.mjs: renew compile examples/01-renewal-2026.renew --module\n" + Renew.compile(src1, { module: true }));
const m = await import(join(root, "examples/embed/renewal-2026.mjs"));
eq("embed module default run", m.run().blocks.find((b) => b.text && b.text.startsWith("break even")).value, 4.889);
eq("embed module with an input", m.run({ discount: "1%" }).blocks.find((b) => b.text && b.text.startsWith("break even")).value, 5.388);
const html = readFileSync(join(root, "examples/embed.html"), "utf8");
ok("embed page imports the module", html.includes('import { run } from "./embed/renewal-2026.mjs";'));
ok("embed page has no interpreter", !html.includes("renew.js") && !html.includes("kernel.js"));
ok("embed page reads raw numbers, not text", html.includes("t.raw.find") && html.includes("be.value"));
ok("embed page uses Penn Blue and Penn Red", html.includes("#011F5B") && html.includes("#990000"));
ok("embed page chart has a text alternative", html.includes('role="img" aria-labelledby="svg-title svg-desc"'));
done("json and embed");
