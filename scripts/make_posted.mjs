// Turns data/posted_rates.json into src/posted_rates.js so the browser and Node load the same table.
import { readFileSync, writeFileSync } from "fs";
const d = JSON.parse(readFileSync(new URL("../data/posted_rates.json", import.meta.url)));
const js = "// Generated by scripts/make_posted.mjs from data/posted_rates.json. Source: " + d.url + "\n" +
  "(function (root) { const data = " + JSON.stringify(d) + ";\n" +
  "if (typeof module !== \"undefined\" && module.exports) module.exports = data; root.RENEW_POSTED = data; })(typeof globalThis !== \"undefined\" ? globalThis : this);\n";
writeFileSync(new URL("../src/posted_rates.js", import.meta.url), js);
console.log("wrote src/posted_rates.js with " + d.dates.length + " weeks");
